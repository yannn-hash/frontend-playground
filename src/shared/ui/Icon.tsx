export type IconName = keyof typeof icons;
export function Icon({
  name,
  size = 18,
  ...props
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const Component = icons[name as IconName] ?? Code2;
  return <Component size={size} strokeWidth={1.7} aria-hidden="true" {...props} />;
}
